def system_prompt(remaining_calls):
    budget = f"\nОсталось вызовов MCP: {remaining_calls}."
    if remaining_calls == 0:
        return SYSTEM + budget + "\n" + FINAL_STEP_NOTE
    return SYSTEM + budget + " Не превышай этот остаток."


